-- PokeChiacchere: notifiche locali sincronizzate tramite Supabase
-- Esegui questo script in Supabase > SQL Editor prima di provare il nuovo pulsante.

create table if not exists public.partner_notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  sender_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists partner_notifications_created_at_idx
  on public.partner_notifications (created_at);

alter table public.partner_notifications enable row level security;

-- Gli utenti autenticati possono leggere i messaggi per ricevere la notifica locale.
drop policy if exists "Authenticated users can read partner notifications"
  on public.partner_notifications;
create policy "Authenticated users can read partner notifications"
  on public.partner_notifications
  for select
  to authenticated
  using (true);

-- Solo l'account proprietario configurato può inviare messaggi.
drop policy if exists "Owner can insert partner notifications"
  on public.partner_notifications;
create policy "Owner can insert partner notifications"
  on public.partner_notifications
  for insert
  to authenticated
  with check (auth.uid() = '01bf546e-bf28-46ac-8370-b4fe30d8a8fd'::uuid);

-- Nessuna policy UPDATE/DELETE: i messaggi inviati non possono essere modificati o rimossi dall'app.
grant select, insert on public.partner_notifications to authenticated;
grant usage, select on sequence public.partner_notifications_id_seq to authenticated;
