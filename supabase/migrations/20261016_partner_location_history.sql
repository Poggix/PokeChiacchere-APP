-- Storico dei punti GPS per la cronologia degli spostamenti.
create table if not exists public.partner_location_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  latitude double precision not null,
  longitude double precision not null,
  accuracy double precision,
  recorded_at timestamptz not null default now(),
  battery_level integer,
  source text not null default 'ios_core_location'
);

create index if not exists partner_location_history_user_time_idx
  on public.partner_location_history (user_id, recorded_at desc);

alter table public.partner_location_history enable row level security;

drop policy if exists "Users insert own location history" on public.partner_location_history;
create policy "Users insert own location history"
  on public.partner_location_history for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users read own or owner reads partner history" on public.partner_location_history;
create policy "Users read own or owner reads partner history"
  on public.partner_location_history for select to authenticated
  using (
    auth.uid() = user_id
    or auth.uid() = '01bf546e-bf28-46ac-8370-b4fe30d8a8fd'::uuid
  );
